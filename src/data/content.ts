// Helper functions for easy querying
export function getAllContent(): ContentItem[] {
  return CONTENT_DATABASE;
}

export function getContentBySlug(slug: string): ContentItem | undefined {
  return CONTENT_DATABASE.find((item) => item.slug === slug);
}

export function getContentByCategory(category: string): ContentItem[] {
  return CONTENT_DATABASE.filter((item) => item.category === category);
}

export function getContentByDeity(deity: string): ContentItem[] {
  return CONTENT_DATABASE.filter((item) => item.deity === deity);
}

export function getFeaturedContent(): ContentItem[] {
  return CONTENT_DATABASE.filter((item) => item.featured);
}

export function getMantraOfTheDay(): ContentItem {
  const eligible = CONTENT_DATABASE.filter((item) => item.dailyMantraEligible);
  if (eligible.length === 0) return CONTENT_DATABASE[0];

  // Deterministic daily selection based on current date
  const now = new Date();
  const dayOfYear = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  const index = Math.abs(dayOfYear) % eligible.length;
  return eligible[index];
}
